"""Generate docs/metrics.md from eval/results/*.json.

Never edit docs/metrics.md by hand: it is regenerated by `make eval`.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval" / "results"


def load(name: str):
    path = RESULTS / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _pct(x):
    return f"{100 * x:.1f}%"


def _ci(level):
    lo, hi = level.get("f1_ci95", (0.0, 0.0))
    return f"{_pct(lo)}–{_pct(hi)}"


def _rate_ci(block):
    lo, hi = block.get("ci95", (block.get("rate", 0.0), block.get("rate", 0.0)))
    return f"{_pct(lo)}–{_pct(hi)}"


def _f1(level):
    return _pct(level["f1"])


def _f1_ci(level):
    if "f1_ci95" in level:
        return f"{_pct(level['f1'])} (CI {_ci(level)})"
    return _pct(level["f1"])


def _rate(block):
    return f"{_pct(block['rate'])} (CI {_rate_ci(block)})"


def main() -> int:
    meddocan = load("meddocan.json")
    carmen = load("carmen_pukara.json")
    presidio_meddocan = load("presidio_meddocan.json")
    presidio_carmen = load("presidio_carmen.json")
    abl = {
        "regex": load("ablate_dev_regex.json"),
        "bert": load("ablate_dev_bert.json"),
        "combined": load("ablate_dev_combined_nopresidio.json"),
        "combined_presidio": load("ablate_dev_combined_presidio.json"),
    }
    promptbench = load("promptbench.json")
    promptbench_heldout = load("promptbench_heldout.json")
    utility = load("utility.json")
    cost = load("cost.json")

    lines = [
        "# Evaluation",
        "",
        "> Generated by `make eval` from `eval/results/*.json`. Do not edit by hand.",
        "",
        "Pukara's anonymization engine detects PHI with a BERT model",
        "(`bsc-bio-ehr-es-carmen-anon`) plus regex rules; Microsoft Presidio is an",
        "optional third component (`PUKARA_ENABLE_PRESIDIO=1`). All numbers below",
        "are produced by scripts in `eval/` and versioned under `eval/results/`.",
        "",
        "## Contamination status",
        "",
        "- **CARMEN-I is retired as a headline metric**: the model was fine-tuned on",
        "  CARMEN-I and no public train/test split could be determined.",
        "- **MEDDOCAN is clean**: the model was not trained on MEDDOCAN. `train`",
        "  (500 docs) is burned (regexes were derived from it) and not reported;",
        "  `dev` (250) is for development/ablations; `test` (250) is the only",
        "  reported split, run once.",
        "",
        "## MEDDOCAN test (out-of-distribution, single run)",
        "",
    ]

    if meddocan:
        pm = presidio_meddocan
        lines += [
            "_Rows: **Pukara** (`meddocan.json`) and the **Presidio standalone "
            "baseline** (`presidio_meddocan.json`), same evaluator, same metrics._",
            "",
            "| Metric | Pukara | Presidio |",
            "|---|---|---|",
            f"| Word F1 | {_f1_ci(meddocan['word_level'])} | {_f1_ci(pm['word_level']) if pm else '—'} |",
            f"| Span strict F1 | {_f1(meddocan['span_strict'])} | {_f1(pm['span_strict']) if pm else '—'} |",
            f"| Span relaxed F1 | {_f1_ci(meddocan['span_relaxed'])} | {_f1_ci(pm['span_relaxed']) if pm else '—'} |",
            f"| PHI neutralization | {_rate(meddocan['phi_neutralization'])} | {_rate(pm['phi_neutralization']) if pm else '—'} |",
            f"| Leakage wide | {_rate(meddocan['leakage']['wide'])} | {_rate(pm['leakage']['wide']) if pm else '—'} |",
            f"| Leakage direct | {_rate(meddocan['leakage']['direct'])} | {_rate(pm['leakage']['direct']) if pm else '—'} |",
            "",
            f"- Pukara revision `{meddocan['code_revision'][:12]}`"
            + (f", Presidio revision `{pm['code_revision'][:12]}`." if pm else "."),
            "",
        ]

        if pm:
            labels = sorted(set(meddocan["per_class"]) | set(pm["per_class"]))
            lines += [
                "### Per-class (span strict): Pukara vs Presidio",
                "",
                "| Class | Pukara F1 | Pukara P / R | Support | Presidio F1 | Presidio P / R | Support |",
                "|---|---|---|---|---|---|---|",
            ]
            for lab in labels:
                c = meddocan["per_class"].get(lab)
                p = pm["per_class"].get(lab)

                def _cells(x):
                    if not x:
                        return "— | — / — | —"
                    return (
                        f"{_f1(x)} | {_pct(x['precision'])} / {_pct(x['recall'])} "
                        f"| {x['support']}"
                    )

                lines.append(f"| {lab} | {_cells(c)} | {_cells(p)} |")
            wins = [
                lab for lab in labels
                if meddocan["per_class"].get(lab) and pm["per_class"].get(lab)
                and pm["per_class"][lab]["support"] > 0
                and pm["per_class"][lab]["f1"] > meddocan["per_class"][lab]["f1"]
            ]
            lines += [
                "",
                "_Classes where the Presidio baseline wins on strict F1: "
                f"{', '.join(sorted(wins)) if wins else 'none (Pukara wins or ties on every class with gold support)'}._",
                "",
                "_Person names are merged into `NAME` (any person name gets the same "
                "pseudonymisation treatment); see `eval/PROTOCOL.md`. Residual classes "
                "below 10% F1 in Pukara: `ORGANIZATION` has no dedicated regex rule and "
                "the CARMEN-trained BERT predicts few organizations (low support)._",
                "",
            ]

        lines += [
            "### Ablation on dev (not reportable; shows how the configuration was chosen)",
            "",
            "| Configuration | Word F1 | Relaxed F1 | Neutralization | Wide leakage |",
            "|---|---|---|---|---|",
        ]
        for name in ["regex", "bert", "combined", "combined_presidio"]:
            d = abl[name]
            if not d:
                continue
            lines.append(
                f"| {name} | {_pct(d['word_level']['f1'])} | "
                f"{_pct(d['span_relaxed']['f1'])} | "
                f"{_pct(d['phi_neutralization']['rate'])} | "
                f"{_pct(d['leakage']['wide']['rate'])} |"
            )
        lines += [
            "",
            "The frozen configuration is `combined` (BERT + regex, Presidio off): "
            "it maximizes relaxed F1 on dev with wide leakage as tie-breaker.",
            "",
        ]
    else:
        lines += ["No MEDDOCAN results yet.\n"]

    lines += ["## CARMEN-I (secondary, in-distribution upper bound)", ""]
    if carmen:
        pc = presidio_carmen
        lines += [
            "_Pukara: the BERT model is fine-tuned on CARMEN-I; in-distribution, "
            "possible train overlap, upper bound. The Presidio row is the standalone "
            "baseline with the same evaluator._",
            "",
            "| Metric | Pukara | Presidio |",
            "|---|---|---|",
            f"| Documents | {carmen['documents']} | {pc['documents'] if pc else '—'} |",
            f"| Word F1 | {_f1(carmen['word_level'])} | {_f1(pc['word_level']) if pc else '—'} |",
            f"| Span strict F1 | {_f1(carmen['span_strict'])} | {_f1(pc['span_strict']) if pc else '—'} |",
            f"| Span relaxed F1 | {_f1(carmen['span_relaxed'])} | {_f1(pc['span_relaxed']) if pc else '—'} |",
            f"| PHI neutralization | {_pct(carmen['phi_neutralization']['rate'])} | {_pct(pc['phi_neutralization']['rate']) if pc else '—'} |",
            f"| Leakage wide | {_rate(carmen['leakage']['wide'])} | {_rate(pc['leakage']['wide']) if pc else '—'} |",
            f"| Leakage direct | {_rate(carmen['leakage']['direct'])} | {_rate(pc['leakage']['direct']) if pc else '—'} |",
            "_CARMEN-I contains many documents with no gold PHI; the per-document "
            "bootstrap CI of F1/neutralization is therefore dominated by empty "
            "documents and is omitted here (only leakage CI, a document-level mean, "
            "is shown). The full CI arrays are in the JSON files._",
            "",
            "_The external `ramsestein/presidio_carmen` repository is cited only as a "
            "source evaluation (`es_core_news_md`, 1,000 docs, character Jaccard) and "
            "is **not** comparable row-by-row with this table._",
            "",
        ]
    else:
        lines += ["No CARMEN-I results yet.\n"]

    lines += ["## Synthetic prompt benchmark", ""]
    if promptbench:
        ss = promptbench["span_strict"]
        sr = promptbench["span_relaxed"]
        co = promptbench["coreference"]
        lines += [
            f"- Dev templates: {promptbench['n_prompts']} prompts, strict F1 "
            f"{_pct(ss['f1'])}, relaxed F1 {_pct(sr['f1'])}, consistency "
            f"{_pct(co['consistency_rate'])}.",
        ]
    if promptbench_heldout:
        ss = promptbench_heldout["span_strict"]
        sr = promptbench_heldout["span_relaxed"]
        co = promptbench_heldout["coreference"]
        lines += [
            f"- Held-out templates: {promptbench_heldout['n_prompts']} prompts, strict F1 "
            f"{_pct(ss['f1'])}, relaxed F1 {_pct(sr['f1'])}, consistency "
            f"{_pct(co['consistency_rate'])}.",
        ]
    if promptbench and promptbench_heldout:
        diff = round(
            promptbench_heldout["span_relaxed"]["f1"] - promptbench["span_relaxed"]["f1"], 4
        )
        lines += [f"- Dev vs held-out relaxed F1 difference: {diff:+.4f}."]
    lines += [
        "",
        "_Limitations: synthetic and templated (optimistic upper bound); possible "
        "circularity if templates and regex rules share authors. Held-out "
        "categories are described independently of the dev templates._",
        "",
    ]

    lines += ["## Utility preservation (restoration robustness)", ""]
    if utility:
        rt = utility["roundtrip"]
        sp = utility["spurious_restorations"]
        lines += [
            f"- Round-trip exact (`deanonymize(anonymize(x)) == x`): "
            f"{rt['failures']} failures / {rt['texts']} texts ({_pct(rt['rate'])}). "
            "The remaining failures are the adversarial texts with a literal "
            "`[NOMBRE_1]` (audit A9, inherent to the reversible-placeholder design).",
            f"- Spurious restorations: {sp['altered']}/{sp['samples']} legit "
            f"bracket/underscore samples altered ({_pct(sp['rate'])}).",
            "",
            "| Perturbation | Restored | Rate |",
            "|---|---|---|",
        ]
        for name, r in utility["robustness"].items():
            lines.append(f"| {name} | {r['restored']}/{r['total']} | {_pct(r['rate'])} |")
        lines.append("")
    else:
        lines += ["No utility results yet.\n"]

    lines += ["## Cost", ""]
    if cost:
        a = cost["anonymization_latency_ms"]
        lines += [
            f"- Hardware: `{cost['hardware']['cpu']}` / `{cost['hardware']['platform']}`.",
            f"- Anonymization (`{cost.get('mode', 'combined')}`, CPU): "
            f"p50 {a['p50']} ms, p95 {a['p95']} ms over {a['documents']} documents.",
            f"- Client peak memory (tracemalloc, Python only): "
            f"{cost['client_peak_memory_bytes'] / 1024 / 1024:.1f} MiB "
            f"(excludes the BERT weights).",
            "",
            "| Payload | Encrypt+decrypt p50 | p95 |",
            "|---|---|---|",
        ]
        for row in cost["encryption_ms"]:
            lines.append(f"| {row['size_bytes']} B | {row['p50_ms']} ms | {row['p95_ms']} ms |")
        lines.append("")
    else:
        lines += ["No cost results yet.\n"]

    out = ROOT / "docs" / "metrics.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("[metrics] docs/metrics.md generado")
    return 0


if __name__ == "__main__":
    sys.exit(main())
