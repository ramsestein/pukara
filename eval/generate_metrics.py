"""Generate docs/metrics.md from eval/results/*.json.

Never edit docs/metrics.md by hand: it is regenerated by `make eval`.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval" / "results"


def load(name: str):
    path = RESULTS / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _pct(x):
    return f"{100 * x:.1f}%"


def _ci(level):
    lo, hi = level.get("f1_ci95", (0.0, 0.0))
    return f"{_pct(lo)}–{_pct(hi)}"


def _rate_ci(block):
    lo, hi = block.get("ci95", (block.get("rate", 0.0), block.get("rate", 0.0)))
    return f"{_pct(lo)}–{_pct(hi)}"


def _f1(level):
    return _pct(level["f1"])


def _f1_ci(level):
    if "f1_ci95" in level:
        return f"{_pct(level['f1'])} (CI {_ci(level)})"
    return _pct(level["f1"])


def _rate(block):
    return f"{_pct(block['rate'])} (CI {_rate_ci(block)})"


def main() -> int:
    meddocan = load("meddocan.json")
    carmen = load("carmen_pukara.json")
    presidio_meddocan = load("presidio_meddocan.json")
    presidio_es_meddocan = load("presidio_es_meddocan.json")
    presidio_carmen = load("presidio_carmen.json")
    presidio_es_carmen = load("presidio_es_carmen.json")
    over_redaction_test = load("over_redaction_test.json")
    over_redaction_test_presidio = load("over_redaction_test_presidio.json")
    over_redaction_test_presidio_es = load("over_redaction_test_presidio_es.json")
    over_redaction_dev = load("over_redaction_dev.json")
    abl = {
        "regex": load("ablate_dev_regex.json"),
        "bert": load("ablate_dev_bert.json"),
        "combined": load("ablate_dev_combined_nopresidio.json"),
        "combined_presidio": load("ablate_dev_combined_presidio.json"),
    }
    promptbench = load("promptbench.json")
    promptbench_heldout = load("promptbench_heldout.json")
    utility = load("utility.json")
    cost = load("cost.json")

    lines = [
        "# Evaluation",
        "",
        "> Generated by `make eval` from `eval/results/*.json`. Do not edit by hand.",
        "",
        "Pukara's anonymization engine detects PHI with a BERT model",
        "(`bsc-bio-ehr-es-carmen-anon`) plus regex rules; Microsoft Presidio is an",
        "optional third component (`PUKARA_ENABLE_PRESIDIO=1`). All numbers below",
        "are produced by scripts in `eval/` and versioned under `eval/results/`.",
        "",
        "## Contamination status",
        "",
        "- **CARMEN-I is retired as a headline metric**: the model was fine-tuned on",
        "  CARMEN-I and no public train/test split could be determined.",
        "- **MEDDOCAN is clean**: the model was not trained on MEDDOCAN. `train`",
        "  (500 docs) is burned (regexes were derived from it) and not reported;",
        "  `dev` (250) is for development/ablations; `test` (250) is the only",
        "  reported split, run once.",
        "",
        "## MEDDOCAN test (out-of-distribution, single run)",
        "",
    ]

    if meddocan:
        systems = [
            ("Pukara", meddocan),
            ("Presidio (OOTB)", presidio_meddocan),
            ("Presidio (ES)", presidio_es_meddocan),
        ]
        lines += [
            "_Pukara vs the Presidio standalone baselines (out-of-the-box and "
            "configured for Spanish), same evaluator, same metrics._",
            "",
            "| Metric | " + " | ".join(n for n, _ in systems) + " |",
            "|" + "---|" * (len(systems) + 1),
        ]

        def _row(fn):
            return " | ".join(fn(d) if d else "—" for _, d in systems)

        lines += [
            f"| Word F1 | {_row(lambda d: _f1_ci(d['word_level']))} |",
            f"| Span strict F1 | {_row(lambda d: _f1(d['span_strict']))} |",
            f"| Span relaxed F1 | {_row(lambda d: _f1_ci(d['span_relaxed']))} |",
            f"| PHI neutralization | {_row(lambda d: _rate(d['phi_neutralization']))} |",
            f"| Leakage wide | {_row(lambda d: _rate(d['leakage']['wide']))} |",
            f"| Leakage direct | {_row(lambda d: _rate(d['leakage']['direct']))} |",
            "",
            f"- Pukara revision `{meddocan['code_revision'][:12]}`; "
            f"Presidio revision `{presidio_meddocan['code_revision'][:12] if presidio_meddocan else '—'}`; "
            f"Presidio ES revision `{presidio_es_meddocan['code_revision'][:12] if presidio_es_meddocan else '—'}`.",
            "",
        ]

        labels = sorted(set().union(*[
            set((d or {}).get("per_class", {})) for _, d in systems
        ]))
        lines += [
            "### Per-class (span strict)",
            "",
            "| Class | " + " | ".join(
                f"{n} F1 | {n} P / R | {n} support" for n, _ in systems) + " |",
            "|" + "---|" * (3 * len(systems) + 1),
        ]
        for lab in labels:
            cells = []
            for _, d in systems:
                x = (d or {}).get("per_class", {}).get(lab)
                if x:
                    cells.append(
                        f"{_f1(x)} | {_pct(x['precision'])} / {_pct(x['recall'])} "
                        f"| {x['support']}"
                    )
                else:
                    cells.append("— | — / — | —")
            lines.append(f"| {lab} | " + " | ".join(cells) + " |")

        es_wins = [
            lab for lab in labels
            if meddocan["per_class"].get(lab)
            and presidio_es_meddocan
            and presidio_es_meddocan["per_class"].get(lab)
            and presidio_es_meddocan["per_class"][lab]["support"] > 0
            and presidio_es_meddocan["per_class"][lab]["f1"] > meddocan["per_class"][lab]["f1"]
        ]
        lines += [
            "",
            "_Classes where the configured Presidio (ES) baseline wins on strict F1: "
            f"{', '.join(sorted(es_wins)) if es_wins else 'none (Pukara wins or ties on every class with gold support)'}._",
            "",
            "_Person names are merged into `NAME` (any person name gets the same "
            "pseudonymisation treatment); see `eval/PROTOCOL.md`._",
            "",
            "_Why Presidio (ES) `ID` is 0 %: MEDDOCAN `test` contains no DNI/NIE-shaped "
            "identifiers. Of the 754 gold `ID` spans, 741 are numeric-only (history "
            "numbers, social-security numbers, plain numbers) and 13 are non-numeric "
            "annotation artifacts; none has the 8-digit + control-letter shape that "
            "`EsNifRecognizer`/`EsNieRecognizer` require. The NIF recognizer would also "
            "validate the control letter, but no span even reaches that check — the zero "
            "recall is a format mismatch, not a checksum rejection._",
            "",
        ]

        # Desglose de la fuga amplia por clase (por sistema).
        attr_labels = sorted({k for _, d in systems if d
                              for k in (d["leakage"]["wide"].get("attribution") or {})},
                             key=lambda k: (k != "multiple", k))
        lines += [
            "### Leakage wide attribution (which class causes the leak)",
            "",
            "| Attribution | " + " | ".join(n for n, _ in systems) + " |",
            "|" + "---|" * (len(systems) + 1),
        ]
        for k in attr_labels:
            row = []
            for _, d in systems:
                a = (d["leakage"]["wide"].get("attribution") or {}).get(k) if d else None
                row.append(_rate(a) if a else "—")
            lines.append(f"| {k} | " + " | ".join(row) + " |")
        lines += [
            "",
            "_`solo_<CLASS>` = documents whose wide leak is caused only by that class; "
            "`multiple` = documents leaking more than one class._",
            "",
        ]

        lines += [
            "### Ablation on dev (not reportable; shows how the configuration was chosen)",
            "",
            "| Configuration | Word F1 | Relaxed F1 | Neutralization | Wide leakage |",
            "|---|---|---|---|---|",
        ]
        for name in ["regex", "bert", "combined", "combined_presidio"]:
            d = abl[name]
            if not d:
                continue
            lines.append(
                f"| {name} | {_pct(d['word_level']['f1'])} | "
                f"{_pct(d['span_relaxed']['f1'])} | "
                f"{_pct(d['phi_neutralization']['rate'])} | "
                f"{_pct(d['leakage']['wide']['rate'])} |"
            )
        lines += [
            "",
            "The frozen configuration is `combined` (BERT + regex, Presidio off): "
            "it maximizes relaxed F1 on dev with wide leakage as tie-breaker.",
            "",
        ]
    else:
        lines += ["No MEDDOCAN results yet.\n"]

    lines += ["## CARMEN-I (secondary, in-distribution upper bound)", ""]
    if carmen:
        systems = [
            ("Pukara", carmen),
            ("Presidio (OOTB)", presidio_carmen),
            ("Presidio (ES)", presidio_es_carmen),
        ]
        lines += [
            "_Pukara: the BERT model is fine-tuned on CARMEN-I; in-distribution, "
            "possible train overlap, upper bound. Presidio rows are the standalone "
            "baselines with the same evaluator._",
            "",
            "| Metric | " + " | ".join(n for n, _ in systems) + " |",
            "|" + "---|" * (len(systems) + 1),
        ]

        def _row(fn):
            return " | ".join(fn(d) if d else "—" for _, d in systems)

        lines += [
            f"| Documents | {_row(lambda d: str(d['documents']))} |",
            f"| Word F1 | {_row(lambda d: _f1_ci(d['word_level']))} |",
            f"| Span strict F1 | {_row(lambda d: _f1(d['span_strict']))} |",
            f"| Span relaxed F1 | {_row(lambda d: _f1_ci(d['span_relaxed']))} |",
            f"| PHI neutralization | {_row(lambda d: _rate(d['phi_neutralization']))} |",
            f"| Leakage wide | {_row(lambda d: _rate(d['leakage']['wide']))} |",
            f"| Leakage direct | {_row(lambda d: _rate(d['leakage']['direct']))} |",
            "",
            "_The external `ramsestein/presidio_carmen` repository is cited only as a "
            "source evaluation (`es_core_news_md`, 1,000 docs, character Jaccard) and "
            "is **not** comparable row-by-row with this table._",
            "",
        ]
    else:
        lines += ["No CARMEN-I results yet.\n"]

    lines += ["## Over-redaction (non-PHI tokens altered)", ""]
    if over_redaction_test:
        lines += [
            "Domain-agnostic metric: share of whitespace tokens that are **not** PHI "
            "in gold but fall inside a predicted span (lower is better).",
            "",
            "| Split | Pukara | Presidio (OOTB) | Presidio (ES) |",
            "|---|---|---|---|",
            f"| MEDDOCAN test | {_rate(over_redaction_test['over_redaction'])} | "
            f"{_rate(over_redaction_test_presidio['over_redaction']) if over_redaction_test_presidio else '—'} | "
            f"{_rate(over_redaction_test_presidio_es['over_redaction']) if over_redaction_test_presidio_es else '—'} |",
            "",
        ]
        if over_redaction_dev:
            b = over_redaction_dev["breakdown"]["by_source"]
            total = over_redaction_dev["breakdown"]["over_redacted_tokens"]
            parts = [f"`{k}` {v} tokens ({_pct(v / total)})" for k, v in b.items()]
            lines += [
                f"Dev (diagnostic, not reportable): rate "
                f"{_rate(over_redaction_dev['over_redaction'])}; per-component "
                f"breakdown — " + ", ".join(parts) + ".",
                "",
            ]
    else:
        lines += ["No over-redaction results yet.\n"]

    lines += ["## Synthetic prompt benchmark", ""]
    if promptbench:
        ss = promptbench["span_strict"]
        sr = promptbench["span_relaxed"]
        co = promptbench["coreference"]
        lines += [
            f"- Dev templates: {promptbench['n_prompts']} prompts, strict F1 "
            f"{_pct(ss['f1'])}, relaxed F1 {_pct(sr['f1'])}, consistency "
            f"{_pct(co['consistency_rate'])}.",
        ]
    if promptbench_heldout:
        ss = promptbench_heldout["span_strict"]
        sr = promptbench_heldout["span_relaxed"]
        co = promptbench_heldout["coreference"]
        lines += [
            f"- Held-out templates: {promptbench_heldout['n_prompts']} prompts, strict F1 "
            f"{_pct(ss['f1'])}, relaxed F1 {_pct(sr['f1'])}, consistency "
            f"{_pct(co['consistency_rate'])}.",
        ]
    if promptbench and promptbench_heldout:
        diff = round(
            promptbench_heldout["span_relaxed"]["f1"] - promptbench["span_relaxed"]["f1"], 4
        )
        lines += [f"- Dev vs held-out relaxed F1 difference: {diff:+.4f}."]
    lines += [
        "",
        "_Limitations: synthetic and templated (optimistic upper bound); possible "
        "circularity if templates and regex rules share authors. Held-out "
        "categories are described independently of the dev templates._",
        "",
    ]

    lines += ["## Utility preservation (restoration robustness)", ""]
    if utility:
        rt = utility["roundtrip"]
        lines += [
            f"- Round-trip exact (`deanonymize(anonymize(x)) == x`): "
            f"{rt['failures']} failures / {rt['texts']} texts ({_pct(rt['rate'])}). "
            "Literal placeholders in the input are escaped on anonymize and "
            "unescaped after deanonymize, so round-trip is exact.",
            "",
        ]
        for mode in ("strict", "lenient"):
            rob = utility["robustness"][mode]
            lines += [
                f"### Robustness — restore mode `{mode}`",
                "",
                "| Perturbation | Restored | Rate |",
                "|---|---|---|",
            ]
            for name, r in rob.items():
                lines.append(
                    f"| {name} | {r['restored']}/{r['total']} | {_pct(r['rate'])} |")
            lines.append("")

        lines += [
            "### Spurious restorations (placeholder-free texts altered by `deanonymize`)",
            "",
            "| Mode | Composition | Altered | Rate | Chars altered |",
            "|---|---|---|---|---|",
        ]
        for mode in ("strict", "lenient"):
            for comp in ("natural", "adversarial"):
                s = utility["spurious_restorations"][mode][comp]
                lines.append(
                    f"| {mode} | {comp} | {s['altered']}/{s['samples']} | "
                    f"{_rate(s)} | {_pct(s['char_rate'])} |"
                )
        lines += [
            "",
            "_`strict` (default) requires both brackets; `lenient` also recovers "
            "single/lost brackets at word boundaries, never over a token already "
            "present in the original prompt (see `docs/client.md`). `natural` = "
            "code/JSON/SQL/CSV without tag-like tokens; `adversarial` = samples with "
            "deliberately inserted tag-like tokens (`nombre_1`, `[ID_2`, `FECHA_3]`).",
            "",
        ]
    else:
        lines += ["No utility results yet.\n"]

    lines += ["## Cost", ""]
    if cost:
        a = cost["anonymization_latency_ms"]
        lines += [
            f"- Hardware: `{cost['hardware']['cpu']}` / `{cost['hardware']['platform']}`.",
            f"- Anonymization (`{cost.get('mode', 'combined')}`, CPU): "
            f"p50 {a['p50']} ms, p95 {a['p95']} ms over {a['documents']} documents.",
            f"- Client peak memory (tracemalloc, Python only): "
            f"{cost['client_peak_memory_bytes'] / 1024 / 1024:.1f} MiB "
            f"(excludes the BERT weights).",
            "",
            "| Payload | Encrypt+decrypt p50 | p95 |",
            "|---|---|---|",
        ]
        for row in cost["encryption_ms"]:
            lines.append(f"| {row['size_bytes']} B | {row['p50_ms']} ms | {row['p95_ms']} ms |")
        lines.append("")
    else:
        lines += ["No cost results yet.\n"]

    out = ROOT / "docs" / "metrics.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("[metrics] docs/metrics.md generado")
    return 0


if __name__ == "__main__":
    sys.exit(main())
