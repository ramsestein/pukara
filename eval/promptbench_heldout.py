"""Held-out synthetic prompt benchmark (Phase F).

Templates generated by construction from a DESCRIPTION of categories (without
looking at the development templates), with a different seed (2024). They are
not read nor adjusted during Phase C.

Circularity declaration is kept: these are still synthetic and templated, so
they are an optimistic upper bound; the same authors wrote the regex rules and
the template categories.
"""
from __future__ import annotations

import datetime
import json
import random
import subprocess
import sys
from pathlib import Path

from eval import common
from eval.promptbench import make_ids, make_person


def generate_heldout_prompts(seed: int = 2024, n: int = 2500):
    """Return held-out prompts with exact gold spans by construction.

    Categories (described, not copied from the dev set):
      1. referral note      — "Paciente X, NHC Y, remitido a Servicio Z"
      2. administrative email — "Asunto: cita de X (DNI) ..."
      3. tabular registry   — "| nombre | dni | nhc | teléfono |"
      4. informal dictation — "oye, el paciente X con DNI ..."
      5. lab label          — "MUESTRA: X · NHC Y · fecha ..."
    """
    rng = random.Random(seed)
    prompts = []
    for i in range(n):
        p = make_person(rng, i)
        ids = make_ids(rng, i)
        country = ["España", "México", "Argentina", "Colombia"][i % 4]
        city = ["Madrid", "Barcelona", "Valencia", "Sevilla"][i % 4]

        if i % 5 == 0:
            segs = [
                ("Nota de derivación del paciente ", None, None),
                (p["name"], "NAME", "person"),
                (", NHC ", None, None),
                (ids["nhc"], "ID", "nhc"),
                (", remitido al Servicio de Cardiología. Nacido el ", None, None),
                ("03/05/1950", "DATE", "dob"),
                (".", None, None),
            ]
        elif i % 5 == 1:
            segs = [
                ("Asunto: cita de ", None, None),
                (p["name"], "NAME", "person"),
                (" (", None, None),
                (ids["dni"], "ID", "dni"),
                ("). Contacto: ", None, None),
                (ids["phone"], "PHONE", "phone"),
                (".", None, None),
            ]
        elif i % 5 == 2:
            segs = [
                ("| nombre | dni | nhc | teléfono |\n| ", None, None),
                (p["name"], "NAME", "person"),
                (" | ", None, None),
                (ids["dni"], "ID", "dni"),
                (" | ", None, None),
                (ids["nhc"], "ID", "nhc"),
                (" | ", None, None),
                (ids["phone"], "PHONE", "phone"),
                (" |", None, None),
            ]
        elif i % 5 == 3:
            segs = [
                ("oye, el paciente ", None, None),
                (p["lower"], "NAME", "person"),
                (" con DNI ", None, None),
                (ids["dni"], "ID", "dni"),
                (", de ", None, None),
                (city, "LOCATION", "city"),
                (", ", None, None),
                (country, "LOCATION", "country"),
                (".", None, None),
            ]
        else:
            segs = [
                ("MUESTRA: ", None, None),
                (p["upper"], "NAME", "person"),
                (" · NHC ", None, None),
                (ids["nhc"], "ID", "nhc"),
                (" · ", None, None),
                ("12/03/2024", "DATE", "sample"),
                (" · correo ", None, None),
                ("lab@example.com", "EMAIL", "email"),
                (".", None, None),
            ]

        text = "".join(s for s, _, _ in segs)
        gold = []
        mentions = {}
        pos = 0
        for surface, label, eid in segs:
            start = pos
            end = pos + len(surface)
            if label is not None:
                gold.append({"start": start, "end": end, "label": label,
                             "text": surface})
                mentions.setdefault(eid, []).append((surface, start, end, label))
            pos = end

        prompts.append({"id": i, "text": text, "gold": gold, "mentions": mentions})
    return prompts


def main() -> int:
    prompts = generate_heldout_prompts()
    predictor = common.Predictor("combined")

    strict_tp = 0
    relaxed_tp = 0
    total_gold = 0
    total_pred = 0
    consistent = 0
    consistent_total = 0
    collisions = 0

    for prompt in prompts:
        text = prompt["text"]
        gold = prompt["gold"]
        _, text_to_ph = predictor.anonymize(text)
        pred = predictor.detect(text)

        total_gold += len(gold)
        total_pred += len(pred)
        strict_tp += _count(common._span_exact, gold, pred)
        relaxed_tp += _count(common._span_overlap, gold, pred)

        for _eid, mentions in prompt["mentions"].items():
            phs = {text_to_ph[s] for s, _s, _e, _l in mentions if s in text_to_ph}
            if phs:
                consistent_total += 1
                if len(phs) == 1:
                    consistent += 1

        ph_to_eid = {}
        for eid, mentions in prompt["mentions"].items():
            for surface, _s, _e, _l in mentions:
                ph = text_to_ph.get(surface)
                if ph is not None:
                    prev = ph_to_eid.get(ph)
                    if prev is not None and prev != eid:
                        collisions += 1
                    ph_to_eid[ph] = eid

    strict = _prf(strict_tp, total_pred - strict_tp, total_gold - strict_tp)
    relaxed = _prf(relaxed_tp, total_pred - relaxed_tp, total_gold - relaxed_tp)

    result = {
        "script": "eval/promptbench_heldout.py",
        "generated": datetime.datetime.utcnow().isoformat() + "Z",
        "code_revision": _git(),
        "mode": "combined",
        "seed": 2024,
        "n_prompts": len(prompts),
        "span_strict": strict,
        "span_relaxed": relaxed,
        "coreference": {
            "consistent_entities": consistent,
            "total_entities_with_detected_mentions": consistent_total,
            "consistency_rate": round(_div(consistent, consistent_total), 4),
        },
        "collisions": collisions,
        "limitations": [
            "Synthetic and templated: optimistic upper bound.",
            "Potential circularity if templates and regex rules share authors.",
            "Held-out categories described independently of the dev templates.",
        ],
    }

    out = Path("eval/results/promptbench_heldout.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n",
                   encoding="utf-8")
    print(
        f"[promptbench-heldout] {len(prompts)} prompts. relaxed F1="
        f"{relaxed['f1']:.4f}, consistency="
        f"{result['coreference']['consistency_rate']:.4f}"
    )
    return 0


def _count(matcher, gold, pred):
    matched_gold = set()
    matched_pred = set()
    for gi, g in enumerate(gold):
        for pi, p in enumerate(pred):
            if pi in matched_pred:
                continue
            if matcher(g, p):
                matched_gold.add(gi)
                matched_pred.add(pi)
                break
    return len(matched_gold)


def _prf(tp, fp, fn):
    p = _div(tp, tp + fp)
    r = _div(tp, tp + fn)
    f1 = _div(2 * p * r, p + r)
    return {"precision": round(p, 4), "recall": round(r, 4), "f1": round(f1, 4)}


def _div(a, b):
    return a / b if b else 0.0


def _git():
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=common.ROOT, text=True).strip()
    except Exception:  # noqa: BLE001
        return "unknown"


if __name__ == "__main__":
    sys.exit(main())
